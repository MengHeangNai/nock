import AppKit
import UniformTypeIdentifiers

// MARK: - Clipboard history

/// Text clipboard history. Unpinned items are kept in memory only; pinned items are saved.
final class ClipboardStore: ObservableObject {
    struct Item: Identifiable, Codable, Equatable {
        var id = UUID()
        let text: String
        var date: Date
        var pinned: Bool
    }

    @Published private(set) var items: [Item] = []

    private let maxUnpinned = 100
    private let pinnedKey = "clipboardPinned"
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Markers that password managers and other apps use to say "don't record this copy".
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    init() {
        if let data = UserDefaults.standard.data(forKey: pinnedKey),
           let pinned = try? JSONDecoder().decode([Item].self, from: data) {
            items = pinned
        }
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        record(text)
    }

    private func record(_ text: String) {
        if let index = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: index)
            item.date = Date()
            items.insert(item, at: 0)
        } else {
            items.insert(Item(text: text, date: Date(), pinned: false), at: 0)
        }

        var unpinnedCount = 0
        var trimmed: [Item] = []
        for item in items {
            if !item.pinned {
                unpinnedCount += 1
                if unpinnedCount > maxUnpinned { continue }
            }
            trimmed.append(item)
        }
        items = trimmed
    }

    func copy(_ item: Item) {
        write(item.text)
    }

    /// Puts a transformed copy of the item on the pasteboard. The next poll adds it to the history.
    func copy(_ item: Item, transformedBy transform: ClipboardTransform) -> Result<Void, ClipboardTransform.Failure> {
        transform.apply(to: item.text).map(write)
    }

    private func write(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func togglePin(_ item: Item) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        savePinned()
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        savePinned()
    }

    func clearHistory() {
        items.removeAll { !$0.pinned }
    }

    private func savePinned() {
        let data = try? JSONEncoder().encode(items.filter(\.pinned))
        UserDefaults.standard.set(data, forKey: pinnedKey)
    }
}

// MARK: - Shelf

/// Files dropped on the island. The shelf keeps references; the files stay where they are.
final class ShelfStore: ObservableObject {
    @Published private(set) var files: [URL] = []

    private let key = "shelfPaths"

    init() {
        files = (UserDefaults.standard.stringArray(forKey: key) ?? [])
            .map { URL(fileURLWithPath: $0) }
            .filter { FileManager.default.fileExists(atPath: $0.path) }
    }

    func add(_ providers: [NSItemProvider]) {
        for provider in providers where provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier) {
            _ = provider.loadObject(ofClass: URL.self) { [weak self] url, _ in
                guard let url, url.isFileURL else { return }
                DispatchQueue.main.async { self?.add(url) }
            }
        }
    }

    func add(_ url: URL) {
        let url = url.standardizedFileURL
        guard !files.contains(url) else { return }
        files.append(url)
        save()
    }

    func remove(_ url: URL) {
        files.removeAll { $0 == url }
        save()
    }

    func clear() {
        files.removeAll()
        save()
    }

    private func save() {
        UserDefaults.standard.set(files.map(\.path), forKey: key)
    }
}

// MARK: - Timer

final class IslandTimer: ObservableObject {
    @Published private(set) var endDate: Date?
    @Published private(set) var pausedRemaining: TimeInterval?
    @Published private(set) var didFinish = false

    private var ticker: Timer?

    var isActive: Bool { endDate != nil || pausedRemaining != nil }
    var isPaused: Bool { pausedRemaining != nil }

    func remaining(at now: Date = Date()) -> TimeInterval {
        if let pausedRemaining { return pausedRemaining }
        if let endDate { return max(0, endDate.timeIntervalSince(now)) }
        return 0
    }

    func start(seconds: TimeInterval) {
        didFinish = false
        pausedRemaining = nil
        endDate = Date().addingTimeInterval(seconds)
        ticker?.invalidate()
        ticker = Timer.scheduledTimer(withTimeInterval: 0.25, repeats: true) { [weak self] _ in self?.check() }
    }

    func add(seconds: TimeInterval) {
        if let endDate {
            self.endDate = endDate.addingTimeInterval(seconds)
        } else if let pausedRemaining {
            self.pausedRemaining = pausedRemaining + seconds
        } else {
            start(seconds: seconds)
        }
    }

    func pause() {
        guard let endDate else { return }
        pausedRemaining = max(0, endDate.timeIntervalSinceNow)
        self.endDate = nil
        stopTicker()
    }

    func resume() {
        guard let pausedRemaining else { return }
        start(seconds: pausedRemaining)
    }

    func cancel() {
        endDate = nil
        pausedRemaining = nil
        stopTicker()
    }

    func dismissFinished() {
        didFinish = false
    }

    private func check() {
        guard let endDate, endDate <= Date() else { return }
        self.endDate = nil
        stopTicker()
        didFinish = true
        for step in 0..<3 {
            DispatchQueue.main.asyncAfter(deadline: .now() + Double(step) * 0.7) {
                NSSound(named: "Glass")?.play()
            }
        }
    }

    private func stopTicker() {
        ticker?.invalidate()
        ticker = nil
    }

    static func format(_ seconds: TimeInterval) -> String {
        let total = Int(seconds.rounded(.up))
        let hours = total / 3600
        let minutes = (total % 3600) / 60
        let secs = total % 60
        return hours > 0
            ? String(format: "%d:%02d:%02d", hours, minutes, secs)
            : String(format: "%d:%02d", minutes, secs)
    }
}

